#!/usr/bin/env node
// pnpm speckit: Spec Kit (github/spec-kit) for the ideas in this repository.
//
//   pnpm speckit <idea> [...]          install or refresh the kit in an existing idea
//   pnpm speckit --all                 the same for every idea
//   pnpm speckit --refresh-template    regenerate templates/speckit/kit/ with the `specify` on this machine
//
// A new idea gets the kit from `pnpm new`. This command is for an idea that predates it,
// for one whose kit files were changed or deleted, and for after a template refresh.
// It replaces kit files only: the idea's constitution and specs/ are never touched
// (a missing or unfilled constitution is written from templates/speckit/constitution.md).

import { parseArgs } from "node:util";
import { loadIdea, loadIdeas } from "./lib/manifest.mjs";
import { cliVersion, installSpecKit, kitVersion, refreshKit } from "./lib/speckit.mjs";

const USAGE = "usage: pnpm speckit <idea> [...] | --all | --refresh-template";
const { values, positionals } = parseArgs({
  allowPositionals: true,
  options: { all: { type: "boolean" }, "refresh-template": { type: "boolean" }, help: { type: "boolean", short: "h" } },
});

if (values.help) {
  console.log(USAGE);
  process.exit(0);
}

if (values["refresh-template"]) {
  const was = kitVersion();
  const cli = cliVersion();
  if (cli === null) {
    console.error("error: the Spec Kit CLI (specify) is not installed, and the template is generated by it.");
    console.error("       Install it yourself (see the Decisions in README.md), then run this again.");
    process.exit(1);
  }
  const r = refreshKit();
  if (!r.ok) {
    console.error(`error: specify init failed:\n${r.out.trim().split("\n").slice(-15).join("\n")}`);
    process.exit(1);
  }
  console.log(`templates/speckit/kit: ${was ?? "none"} -> ${r.version} (${r.files} files)`);
  console.log("Next: pnpm test, then pnpm speckit --all to bring existing ideas up to date, then verify.");
  process.exit(0);
}

const names = values.all ? loadIdeas().map((i) => i.dirName) : positionals;
if (names.length === 0) {
  console.error(values.all ? "no ideas yet. Create one with: pnpm new <name>" : USAGE);
  process.exit(values.all ? 0 : 2);
}

let failed = 0;
for (const name of names) {
  const idea = loadIdea(name);
  if (idea.manifest === null) {
    failed++;
    console.error(`FAIL apps/${name}: ${idea.errors.join("; ")}`);
    continue;
  }
  const r = installSpecKit(idea.dir, { name, title: idea.manifest.title ?? name });
  const after = loadIdea(name).errors;
  if (after.length > 0) failed++;
  console.log(`${after.length === 0 ? "ok  " : "FAIL"} apps/${name}: Spec Kit ${r.version}, constitution ${r.constitution}${r.removed.length > 0 ? `, removed ${r.removed.join(", ")}` : ""}`);
  for (const e of after) console.error(`       - ${e}`);
}
process.exit(failed === 0 ? 0 : 1);
